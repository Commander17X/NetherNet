export type GeyserConfigInput = {
  javaHost: string;
  javaPort: number;
  bedrockPort: number;
  webrtcPort: number;
  authMode: "online" | "offline";
  serverName: string;
  publicHost: string;
};

function yamlString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function advertise(host: string, port: number): string {
  const wrapped = host.includes(":") && !host.startsWith("[") ? `[${host}]` : host;
  return `${wrapped}:${port}`;
}

export function renderGeyserConfig(input: GeyserConfigInput): string {
  if (input.authMode !== "online" && input.authMode !== "offline") {
    throw new Error("Geyser auth must be online or offline.");
  }

  const name = input.serverName.replace(/[\r\n"]/g, " ").trim().slice(0, 32) || "NetherNet";
  const motd = `NetherNet · ${name}`.slice(0, 60);

  return `# Generated by NetherNet for one Java server session.
bedrock:
  address: "0.0.0.0"
  port: ${input.bedrockPort}
  webrtc-port: ${input.webrtcPort}
  transport: both
  clone-remote-port: false
  signaling:
    mode: builtin
    stun-discovery: true
    advertise-addresses:
      - ${yamlString(advertise(input.publicHost, input.webrtcPort))}
java:
  address: ${yamlString(input.javaHost)}
  port: ${input.javaPort}
  auth-type: ${input.authMode}
  forward-hostname: false
motd:
  primary-motd: "NetherNet"
  secondary-motd: ${yamlString(motd)}
  passthrough-motd: true
  passthrough-player-counts: true
  integrated-ping-passthrough: true
  ping-passthrough-interval: 3
  max-players: 100
gameplay:
  server-name: "NetherNet"
  show-cooldown: title
  command-suggestions: true
  show-coordinates: true
  emotes-enabled: true
  enable-custom-content: true
  force-resource-packs: true
  enable-integrated-pack: true
  forward-player-ping: false
advanced:
  floodgate-key-file: "key.pem"
  bedrock:
    broadcast-port: ${input.bedrockPort}
    compression-level: 6
    validate-bedrock-login: true
  java:
    use-haproxy-protocol: false
`;
}
